"""
Готовит бонусную комнату из макета «новые ассеты 2(для бонуски)».

    python tools/prep_bonus_room.py

На выходе:

    bonus-room.png   вся сцена целиком: комната из бонусного макета
                     с рамкой барабанов и нижней полосой из основной
    boss-throne.png  BILLY на троне — спрайт в слот маскота

## Почему комната собирается, а не берётся макетом как есть

Макет бонусной комнаты нарисован как готовый экран: свой трон по центру,
свои боковые таблицы, своя нижняя полоса и своё поле барабанов. Поле там
в перспективе и на три ряда — а в игре оно плоское и на четыре (REELS = 5,
ROWS = 4 заложены в мат-модель и в проверенный на десяти миллионах раундов
возврат). Ни подложить своё поле под нарисованное, ни натянуть барабаны
на перспективу нельзя: ячейки не совпадут ни числом, ни формой.

Поэтому от бонусного макета берётся то, ради чего он и рисовался, — сама
комната: стены с неоном, пол, снаряды, бочки. А рамка барабанов и нижняя
полоса переносятся из основной комнаты один в один, вместе с координатами.
Все числа в layout.ts продолжают работать, движок ничего не пересчитывает,
и при переключении комнат на месте остаётся ровно то, что должно, —
интерфейс. Меняется комната вокруг него.

Трон при таком раскладе оказывается за рамкой барабанов, поэтому BILLY
выносится отдельным спрайтом в слот маскота: в основной комнате там стоит
VAN, в бонусной сидит хозяин подземелья. Заодно решается вопрос масштаба —
на макете трон занимает половину экрана, в слоте маскота он ровно к месту.

## Кроп по высоте

Макет 1536x1024 (3:2), сцена 1609x918 (16:9) — лишние строки режутся снизу,
а не сверху. Сверху нельзя: там неоновый знак ♂, ради которого стена и
рисовалась. Снизу — нарисованная нижняя полоса макета, которую всё равно
закрывает своя.
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "новые ассеты 2(для бонуски)"
UI = ROOT / "src" / "assets" / "ui"

STAGE_W, STAGE_H = 1609, 918

# Рамка барабанов на основном фоне. Границы сняты по профилям яркости:
# металл рамки светлее стены, по столбцам он начинается на 438 и кончается
# на 1190, по строкам — 84 и 678. Прямоугольник взят на пару пикселей шире,
# чтобы в него попала вся тёмная кромка рамки, а не только металл.
FRAME = (436, 80, 1192, 682)

# Нижняя полоса интерфейса. Начинается выше PANEL_TOP (676): там кончается
# рамка барабанов, и стык двух переносов приходится на её тёмную кромку,
# а не на открытую стену.
PANEL_TOP = 670

# Колонка правой панели «ПОДЗЕМЕЛЬЕ» — тоже из основной комнаты, и не потому,
# что панель нужна (её кладёт спрайтом движок), а из-за того, что нарисовано
# на макете под ней: своя таблица выплат «GAIN & CHAINS». Панель накрывает её
# не целиком, и над панелью оставался торчать заголовок с первой строкой —
# вторая таблица выплат в углу, поверх которой движок пишет свою.
INFO_COLUMN = (1176, 0, 1469, 596)

# Насколько мягко переносы растворяются в стене бонусной комнаты. Ровная
# граница двух почти чёрных стен всё равно видна как ступенька в тоне,
# а размытая на десяток пикселей — нет.
FEATHER = 10

# Трон с BILLY на макете: x 490..1005, y 5..570. Сверху захвачено неоновое
# кольцо за спинкой (без него трон обрублен по плечи), снизу — сапоги
# и подножие; ниже начинается нарисованное поле барабанов.
THRONE = (490, 5, 1005, 570)


def feathered_mask(size: tuple[int, int], boxes: list[tuple[int, int, int, int]]):
    mask = Image.new("L", size, 0)
    draw = ImageDraw.Draw(mask)
    for box in boxes:
        draw.rectangle(box, fill=255)
    return mask.filter(ImageFilter.GaussianBlur(FEATHER))


def throne_sprite(room: Image.Image) -> Image.Image:
    """Вырезает трон с BILLY мягким краем.

    Жёсткий контур обвести нечем: чистого силуэта у трона нет — за спинкой
    неоновое кольцо, по бокам такая же тёмная кладка, что и вокруг. Зато
    и вырезать начисто незачем: он ложится на такую же тёмную стену бонусной
    комнаты, и растворённый край читается как тень за троном.
    """
    sprite = room.crop(THRONE).convert("RGBA")
    w, h = sprite.size

    mask = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(mask)
    # Снизу край не растворяем: там трон стоит на полу и уходит под нижнюю
    # полосу, размытый низ читался бы висящей в воздухе фигурой.
    draw.rectangle((26, 26, w - 27, h), fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(16))

    sprite.putalpha(mask)
    return sprite


def main() -> int:
    src = SRC / "background_full.png"
    main_bg = UI / "background.png"
    for path in (src, main_bg):
        if not path.exists():
            print(f"  Не найден файл: {path}")
            return 1

    room = Image.open(src).convert("RGB")
    keep_h = round(room.width / (STAGE_W / STAGE_H))
    stage = room.crop((0, 0, room.width, keep_h)).resize((STAGE_W, STAGE_H), Image.LANCZOS)

    base = Image.open(main_bg).convert("RGB").resize((STAGE_W, STAGE_H), Image.LANCZOS)
    mask = feathered_mask(
        (STAGE_W, STAGE_H),
        [FRAME, INFO_COLUMN, (0, PANEL_TOP, STAGE_W, STAGE_H)],
    )
    plate = Image.composite(base, stage, mask)

    UI.mkdir(parents=True, exist_ok=True)
    plate.save(UI / "bonus-room.png")
    throne = throne_sprite(room)
    throne.save(UI / "boss-throne.png")

    print(f"  bonus-room.png   {plate.size[0]}x{plate.size[1]}")
    print(f"  boss-throne.png  {throne.size[0]}x{throne.size[1]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
