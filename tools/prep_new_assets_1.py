def drop_small_components(img: Image.Image, min_size: int) -> None:
    """Топит в прозрачность связные непрозрачные обрывки мельче `min_size` пикселей.

    После жёсткого кропа на безопасную зону это только страховка от одно-двух-
    пиксельных точек сглаживания по краю — не более того.
    """
    w, h = img.size
    px = img.load()
    seen = [[False] * w for _ in range(h)]

    for sy in range(h):
        for sx in range(w):
            if seen[sy][sx] or px[sx, sy][3] == 0:
                continue
            comp: list[tuple[int, int]] = []
            queue = deque([(sx, sy)])
            seen[sy][sx] = True
            while queue:
                x, y = queue.popleft()
                comp.append((x, y))
                for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
                    if 0 <= nx < w and 0 <= ny < h and not seen[ny][nx] and px[nx, ny][3] > 0:
                        seen[ny][nx] = True
                        queue.append((nx, ny))
            if len(comp) < min_size:
                for x, y in comp:
                    r, g, b, _ = px[x, y]
                    px[x, y] = (r, g, b, 0)


def alpha_from_luma(img: Image.Image, lo: int, hi: int) -> None:
    """Делает прозрачность по яркости пикселя, с плавным переходом от lo к hi."""
    px = img.load()
    w, h = img.size
    span = max(1, hi - lo)
    for y in range(h):
        for x in range(w):
            r, g, b, _ = px[x, y]
            luma = max(r, g, b)
            if luma <= lo:
                px[x, y] = (r, g, b, 0)
            elif luma < hi:
                px[x, y] = (r, g, b, int(255 * (luma - lo) / span))


def drop_background_tol(img: Image.Image, tolerance: int) -> None:
    """Как slice_art.drop_background, но с собственным допуском вместо жёстких 46."""
    w, h = img.size
    px = img.load()
    seed = px[0, 0][:3]
    seen = [[False] * w for _ in range(h)]
    queue: deque[tuple[int, int]] = deque()
    for x in range(w):
        queue.append((x, 0))
        queue.append((x, h - 1))
    for y in range(h):
        queue.append((0, y))
        queue.append((w - 1, y))
    while queue:
        x, y = queue.popleft()
        if x < 0 or y < 0 or x >= w or y >= h or seen[y][x]:
            continue
        r, g, b, _ = px[x, y]
        if abs(r - seed[0]) + abs(g - seed[1]) + abs(b - seed[2]) > tolerance:
            continue
        seen[y][x] = True
        px[x, y] = (r, g, b, 0)
        queue.extend(((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)))


