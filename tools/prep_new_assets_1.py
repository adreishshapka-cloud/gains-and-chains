# что и цифра «10», и общей горизонтали для них нет.
# Прямоугольники, которые делаются прозрачными ПОСЛЕ снятия фона.
# Координаты — в системе уже кропнутого изображения.
#
# Нужно там, где обрывок соседней карточки налезает на сам предмет и границей
# кадра его не отделить. У канистры поверх правого верхнего угла лежит край
# чужой пивной кружки.
#
# Именно прозрачными, а не чёрными: чёрный прямоугольник заливка фона потом
# съедает вместе с куском рисунка, к которому он примыкает. На кресте это
# ровно так и вышло — от верхнего левого луча оставался обрубок.
CUT_RECTS: dict[str, list[tuple[int, int, int, int]]] = {
    # Кружка из соседней карточки: в исходнике x 98..133, y 0..32,
    # кроп начинается с x=5. Левее 100 идёт ручка самой канистры — не задеваем.
    "04_oil_can.png": [(95, 0, 150, 33)],
    # Обрывок соседнего значка у наконечника стрелки ♂: в исходнике
    # x 81..88, y 73..92, кроп начинается с (4, 72). Сама стрелка в этих
    # строках не заходит правее x=80.
    "20_male_x1.png": [(77, 1, 85, 21)],
}

# Прозрачность по яркости вместо заливки от краёв: имя файла -> (низ, верх).
# Ниже нижнего порога пиксель полностью прозрачен, выше верхнего — полностью
# непрозрачен, между ними плавный переход.
#
# Нужно ровно одному символу — светящемуся ♂. Он нарисован золотом на чистом
# чёрном, и заливка от краёв на нём не работает ни при каком допуске: большой
# проносит её сквозь тёмные грани кольца, и оно распадается на дуги; маленький
# оставляет вокруг знака чёрное облако свечения. По яркости же разделение
# точное, и разорвать кольцо оно не может в принципе — маска строится
# по каждому пикселю отдельно, без связности.
LUMA_ALPHA: dict[str, tuple[int, int]] = {
    "20_male_x1.png": (14, 58),
}

# Отсев мелких обособленных кусков: имя файла -> минимальный размер в пикселях.
# По умолчанию 6 — это страховка от точек сглаживания по краю.
# Больше нужно там, где в кадр попал обрывок покрупнее: рядом с наконечником
# стрелки ♂ висит кусок соседнего значка примерно в полсотни пикселей.
MIN_COMPONENT: dict[str, int] = {}


def process(
    src_name: str, dest: Path, crop: tuple[int, int, int, int], square: bool, tolerance: int = 46
):
    im = Image.open(SRC / src_name).convert("RGBA").crop(crop)
    if src_name in LUMA_ALPHA:
        alpha_from_luma(im, *LUMA_ALPHA[src_name])
    elif tolerance == 46:
        drop_background(im)
    else:
        drop_background_tol(im, tolerance)
    for cx1, cy1, cx2, cy2 in CUT_RECTS.get(src_name, []):
        for y in range(cy1, min(cy2, im.height)):
            for x in range(cx1, min(cx2, im.width)):
                r, g, b, _ = im.getpixel((x, y))
                im.putpixel((x, y), (r, g, b, 0))
    drop_small_components(im, min_size=MIN_COMPONENT.get(src_name, 6))
    if square:
        save_square(im, dest)
    else:
        box = im.getbbox()
        if box:
            im = im.crop(box)
        dest.parent.mkdir(parents=True, exist_ok=True)
        im.save(dest)
    print(f"  {src_name:32s} -> {dest.relative_to(ROOT)}  {im.size}")


def cut_on_black(
    src_name: str,
    dest: Path,
    crop: tuple[int, int, int, int] | None,
    tolerance: int,
    closing: int,
    span: bool = False,
):
    """Вырезает фигуру со сплошного чёрного фона: заливка от краёв + смыкание маски."""
    import numpy as np

    rgb = Image.open(SRC / src_name).convert("RGB")
    if crop:
        rgb = rgb.crop(crop)
    a = np.asarray(rgb).astype(int)
    h, w, _ = a.shape

    near_bg = np.abs(a - a[0, 0]).sum(axis=2) <= tolerance
    outside = np.zeros((h, w), bool)
    queue: deque[tuple[int, int]] = deque()
    for x in range(w):
        for y in (0, h - 1):
            if near_bg[y, x] and not outside[y, x]:
                outside[y, x] = True
                queue.append((x, y))
    for y in range(h):
        for x in (0, w - 1):
            if near_bg[y, x] and not outside[y, x]:
                outside[y, x] = True
                queue.append((x, y))
    while queue:
        x, y = queue.popleft()
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < w and 0 <= ny < h and not outside[ny, nx] and near_bg[ny, nx]:
                outside[ny, nx] = True
                queue.append((nx, ny))

    keep = ~outside
    if span:
        for y in range(h):
            xs = np.nonzero(keep[y])[0]
            if len(xs):
                keep[y, xs.min() : xs.max() + 1] = True

    mask = Image.fromarray(keep.astype("uint8") * 255)
    if closing:
        side = 2 * closing + 1
        mask = mask.filter(ImageFilter.MaxFilter(side)).filter(ImageFilter.MinFilter(side))
    # Полпикселя размытия по краю: без него контур идёт ступенями,
    # и на светлом участке стены они заметны.
    mask = mask.filter(ImageFilter.GaussianBlur(0.8))

    out = rgb.convert("RGBA")
    out.putalpha(mask)
    box = out.getbbox()
    if box:
        out = out.crop(box)
    dest.parent.mkdir(parents=True, exist_ok=True)
    out.save(dest)
    print(f"  {src_name:32s} -> {dest.relative_to(ROOT)}  {out.size}")


def process_panel(
    src_name: str,
    dest: Path,
    crop: tuple[int, int, int, int],
    blanks: list[tuple[int, int, int, int, int, int]],
):
    """Готовит панель интерфейса: кроп плюс гашение запечённых значений.

    Гашение идёт ДО кропа — прямоугольники обмерены по исходному файлу,
    так их проще перепроверить по нему же.
    """
    full = Image.open(SRC / src_name).convert("RGB")
    for x1, y1, x2, y2, sx1, sx2 in blanks:
        piece = full.crop((sx1, y1, sx2, y2))
        width = sx2 - sx1
        for i, x in enumerate(range(x1, x2, width)):
            part = piece if i % 2 == 0 else piece.transpose(Image.FLIP_LEFT_RIGHT)
            full.paste(part.crop((0, 0, min(width, x2 - x), y2 - y1)), (x, y1))
    im = full.crop(crop).convert("RGBA")
    dest.parent.mkdir(parents=True, exist_ok=True)
    im.save(dest)
    print(f"  {src_name:32s} -> {dest.relative_to(ROOT)}  {im.size}  (панель)")


def main():
    SYMBOLS.mkdir(parents=True, exist_ok=True)
    UI.mkdir(parents=True, exist_ok=True)

    print("Символы:")
    for src_name, dest_name, crop in SYMBOL_JOBS:
        tol = SYMBOL_TOLERANCE.get(src_name, 46)
        process(src_name, SYMBOLS / dest_name, crop, square=True, tolerance=tol)

    print("\nИнтерфейс (вырез):")
    for src_name, dest_name, crop, tol in UI_CUTOUT_JOBS:
        process(src_name, UI / dest_name, crop, square=False, tolerance=tol)

    print("\nФигуры на чёрном фоне:")
    for src_name, dest_name, crop, tol, closing, span in BLACK_CUTOUT_JOBS:
        cut_on_black(src_name, UI / dest_name, crop, tol, closing, span)

    print("\nИнтерфейс (панели целиком):")
    for src_name, dest_name, crop, blanks in UI_PANEL_JOBS:
        process_panel(src_name, UI / dest_name, crop, blanks)

    print("\nБез замены (нет исходника): fist.png — оставлен прежним.")


if __name__ == "__main__":
    main()
