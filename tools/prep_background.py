def patch_region(img: Image.Image, box, blur: int = 3):
    """
    Затирает область цветом её собственных краёв.
    Берём рамку в пару пикселей вокруг, усредняем и заливаем с лёгким размытием —
    на тёмной панели шва не видно, а возиться с текстурой ради этого не стоит.
    """
    x1, y1, x2, y2 = box[:4]
    px = img.load()
    w, h = img.size

    samples = []
    for x in range(max(0, x1 - 3), min(w, x2 + 3)):
        for y in (max(0, y1 - 3), min(h - 1, y2 + 2)):
            samples.append(px[x, y])
    for y in range(max(0, y1 - 3), min(h, y2 + 3)):
        for x in (max(0, x1 - 3), min(w - 1, x2 + 2)):
            samples.append(px[x, y])

    if not samples:
        return
    avg = tuple(sum(c[i] for c in samples) // len(samples) for i in range(3))

    fill = Image.new("RGB", (x2 - x1, y2 - y1), avg)
    img.paste(fill, (x1, y1))

    if blur <= 0:
        return

    # Размываем границу заплатки, чтобы не читался прямоугольник.
    pad = 6
    around = (max(0, x1 - pad), max(0, y1 - pad), min(w, x2 + pad), min(h, y2 + pad))
    blurred = img.crop(around).filter(ImageFilter.GaussianBlur(blur))
    img.paste(blurred, around)


def tile_fill(
    img: Image.Image,
    box: tuple[int, int, int, int],
    tile: Image.Image,
    origin: tuple[int, int] = (0, 0),
) -> None:
    """
    Замащивает прямоугольник повторяющимся куском стены.

    Тайл передаётся готовым, а не вырезается тут же из `img`: к моменту второго
    вызова изображение уже изменено первым, и тайл, взятый «по месту», начал бы
    тиражировать результат предыдущего замощения.

    Сетка отсчитывается не от угла прямоугольника, а от общей точки `origin`.
    Иначе две соседние заплатки начинают ряд каждая от своего угла, и на их
    стыке кладка не сходится — шов виден насквозь.
    """
    tw, th = tile.size
    ox, oy = origin
    x1, y1, x2, y2 = box

    # Первая клетка общей сетки, задевающая прямоугольник.
    start_x = ox + ((x1 - ox) // tw) * tw
    start_y = oy + ((y1 - oy) // th) * th

    y = start_y
    while y < y2:
        x = start_x
        while x < x2:
            # Отражение только по горизонтали, и по номеру клетки В СЕТКЕ,
            # а не по счётчику внутри заплатки: иначе у соседних заплаток
            # чередование разойдётся. Переворот по вертикали пробовали и убрали:
            # у кладки есть верх и низ (перемычки, блики сверху), и
            # перевёрнутый ряд читался как зеркальная полоса-«клякса» через
            # каждые два тайла — глаз цеплялся за неё сильнее, чем за простое
            # повторение, которое она должна была скрыть.
            piece = tile
            if ((x - ox) // tw) % 2:
                piece = piece.transpose(Image.FLIP_LEFT_RIGHT)

            # Края клетки, вылезающие за прямоугольник, отсекаются.
            cx1, cy1 = max(x1 - x, 0), max(y1 - y, 0)
            cx2, cy2 = min(tw, x2 - x), min(th, y2 - y)
            if cx2 > cx1 and cy2 > cy1:
                img.paste(piece.crop((cx1, cy1, cx2, cy2)), (x + cx1, y + cy1))
            x += tw
        y += th


def erase_glow(img: Image.Image, box: tuple[int, int, int, int], threshold: int) -> None:
    """
    Стирает светящуюся надпись, достраивая поле под ней из соседних пикселей.

    Буквы находятся по синему каналу (свечение фиолетовое, поле — тёмное),
    маска расширяется на 2px, чтобы забрать ореол, и дальше дырка затягивается
    усреднением с соседями. Это дискретное решение уравнения Лапласа: значения
    по краю дырки заданы полем, внутри — растягиваются плавно. Поэтому заплатка
    и повторяет подсветку, вместо того чтобы спорить с ней.
    """
    import numpy as np

    x1, y1, x2, y2 = box
    area = np.asarray(img.crop(box), dtype=float)
    # По самому яркому каналу, а не по конкретному: подписи в макете разного
    # цвета — фиолетовая на табличке, золотая в нижней полосе, — а общее
    # у них одно: они ярче своей подложки.
    mask = area.max(axis=2) > threshold

    # Ореол вокруг букв ярче поля, но темнее порога: без расширения маски
    # от надписи остаётся её призрак.
    for _ in range(2):
        grown = mask.copy()
        grown[1:, :] |= mask[:-1, :]
        grown[:-1, :] |= mask[1:, :]
        grown[:, 1:] |= mask[:, :-1]
        grown[:, :-1] |= mask[:, 1:]
        mask = grown

    known = ~mask
    if not known.any():
        return

    fill = area.copy()
    fill[mask] = area[known].mean(axis=0)

    # Итераций хватает, чтобы «протянуть» поле через самую широкую букву:
    # шаг усреднения продвигает границу на пиксель, а буквы здесь ~40px.
    m3 = mask[..., None]
    for _ in range(900):
        pad = np.pad(fill, ((1, 1), (1, 1), (0, 0)), mode="edge")
        avg = (pad[:-2, 1:-1] + pad[2:, 1:-1] + pad[1:-1, :-2] + pad[1:-1, 2:]) / 4
        fill = np.where(m3, avg, fill)

    img.paste(Image.fromarray(fill.round().astype("uint8"), "RGB"), (x1, y1))


def shade_region(
    img: Image.Image, box: tuple[int, int, int, int], top: float, bottom: float
) -> None:
    """Гасит область линейным вертикальным градиентом от `top` к `bottom`."""
    x1, y1, x2, y2 = box
    area = img.crop(box)
    px = area.load()
    h = y2 - y1
    for y in range(h):
        k = top + (bottom - top) * (y / max(1, h - 1))
        for x in range(x2 - x1):
            r, g, b = px[x, y]
            px[x, y] = (int(r * k), int(g * k), int(b * k))
    img.paste(area, (x1, y1))


def main(src: Path):
    sheet = Image.open(src).convert("RGB")
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    # Копия до всех правок: из неё возвращаются куски, которые замощение
    # затронуло по касательной.
    original = sheet.copy()

    # Медиана 3x3 по кирпичному тайлу: в исходном куске стены сидит пара
    # одиночных ярко-розовых точек (блик), и при укладке они выстраивались
    # в правильную сетку крапин по всей заплатке.
    brick = original.crop(BRICK_TILE).filter(ImageFilter.MedianFilter(3))
    for box, source, origin in TILE_FILL:
        # Медиана только кирпичу: в нём сидят одиночные ярко-розовые точки,
        # которые при укладке выстраивались в правильную сетку крапин.
        tile = brick if source == BRICK_TILE else original.crop(source)
        tile_fill(sheet, box, tile, origin or (box[0], box[1]))

    for x1, y1, x2, y2, top, bottom in SHADE:
        shade_region(sheet, (x1, y1, x2, y2), top, bottom)

    # Швы замощения размываются, иначе видна сетка стыков. Только у кладки:
    # у заплатки нижней полосы размытие съело бы её верхнюю и нижнюю кромки.
    # Делается ДО восстановления кусков: иначе размытие пройдётся и по ним,
    # превратив вернувшуюся тумбу в мыло.
    for (x1, y1, x2, y2), source, _ in TILE_FILL:
        if source != BRICK_TILE:
            continue
        area = (max(0, x1 - 2), max(0, y1 - 2), min(sheet.width, x2 + 2), min(sheet.height, y2 + 2))
        sheet.paste(sheet.crop(area).filter(ImageFilter.GaussianBlur(1.2)), area)

    for x1, y1, x2, y2 in RESTORE:
        sheet.paste(original.crop((x1, y1, x2, y2)), (x1, y1))

    for sx, sy, dx, dy, cw, ch in CLONE:
        sheet.paste(sheet.crop((sx, sy, sx + cw, sy + ch)), (dx, dy))

    for src_x, y1, y2, dx1, dx2 in STRETCH:
        column = sheet.crop((src_x, y1, src_x + 1, y2))
        sheet.paste(column.resize((dx2 - dx1, y2 - y1), Image.NEAREST), (dx1, y1))

    for x1, y1, x2, y2, threshold in GLOW_ERASE:
        erase_glow(sheet, (x1, y1, x2, y2), threshold)

    for region in ERASE:
        patch_region(sheet, region[:4], region[4] if len(region) > 4 else 3)

    sheet.save(OUT_DIR / "background.png")
    print(f"  background.png  {sheet.size[0]}x{sheet.size[1]}, стёрто участков: {len(ERASE)}")
    print(f"\n  Готово: {OUT_DIR}")


