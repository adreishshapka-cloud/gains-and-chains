"""
Готовит из папки «новые ассеты 1» три картинки, которые пришли целыми экранами:

    python tools/prep_screens.py

    цепь.png              -> oil-panel.png      секция «OIL UP» нижней полосы
    правила (2).png       -> rules-screen.png   экран правил
    меню.png              -> menu-screen.png    экран настроек
    скипнуть день ног.png -> choice-screen.png  выбор бонуса
    взять монеты.png      -> topup-screen.png   пополнение счёта

Работа одна: **погасить запечённые значения.** На картинках нарисованы
конкретные числа — счётчик цепей, громкость, вся статистика. В игре они живые,
движок пишет свои поверх, поэтому нарисованные закрываются куском фона той же
панели.

Экраны правил, выбора бонуса и пополнения проходят насквозь: живых значений
на них нет вовсе, всё постоянное. Чтобы они не разошлись с мат-моделью молча,
их числа закреплены `src/ui/rulesArt.test.ts`.

Если ассеты перерисуют, координаты придётся снять заново — все они здесь
обмерены по конкретным файлам, а не выведены из чего-то.
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "новые ассеты 1"
UI = ROOT / "src" / "assets" / "ui"

Box = tuple[int, int, int, int]


def cover(img: Image.Image, dest: Box, src: Box, feather: int = 6) -> None:
    """Закрывает прямоугольник куском фона той же панели.

    Кусок размножается по обеим осям с переворотом через раз — фон панелей
    это тёмный камень с редкими царапинами, и при повторе встык царапина
    выдавала бы сетку. Края растворяются: панель неоднородна по яркости
    (по краям темнее), и вставка встык видна ступенькой в тоне.
    """
    x1, y1, x2, y2 = dest
    w, h = x2 - x1, y2 - y1
    piece = img.crop(src)
    pw, ph = piece.size

    patch = Image.new("RGB", (w, h))
    for ty in range(0, h, ph):
        for tx in range(0, w, pw):
            part = piece
            if (tx // pw) % 2:
                part = part.transpose(Image.FLIP_LEFT_RIGHT)
            if (ty // ph) % 2:
                part = part.transpose(Image.FLIP_TOP_BOTTOM)
            patch.paste(part, (tx, ty))

    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).rectangle((feather, feather, w - 1 - feather, h - 1 - feather), fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(feather / 1.6))

    img.paste(patch, (x1, y1), mask)


def glyph(img: Image.Image, box: Box) -> Image.Image:
    """Снимает букву с картинки.

    Снимать нужно ДО того, как затирается старое слово: заплатка кладётся
    поверх и уносит с собой буквы, которые предстоит переставить.
    """
    return img.crop(box)


# ─────────────────────────────────────────────────────────────
# OIL UP
# ─────────────────────────────────────────────────────────────


def oil_panel() -> Image.Image:
    """Секция «OIL UP» с погашенным счётчиком.

    Запечена единица на x 1136..1201, y 411..550. Источник фона — чистое место
    той же ячейки правее цифры: ячейка изнутри однородная, и брать надо
    именно её, а не панель вокруг — панель светлее.
    """
    im = Image.open(SRC / "цепь.png").convert("RGB")
    cover(im, (1110, 390, 1230, 570), (1250, 390, 1370, 570), feather=10)
    return im


# ─────────────────────────────────────────────────────────────
# Правила
# ─────────────────────────────────────────────────────────────


def rules_screen() -> Image.Image:
    """Экран правил — как есть.

    Гасить нечего: на этом экране всё постоянное, живого значения нет ни одного.
    Первая версия макета требовала правок — там были опечатки и устаревшие
    двери, — и они делались прямо в пикселях. Теперь макет перерисован
    начисто, и заплатки выброшены.
    """
    return Image.open(SRC / "правила (2).png").convert("RGB")


# ─────────────────────────────────────────────────────────────
# Настройки
# ─────────────────────────────────────────────────────────────


def menu_screen() -> Image.Image:
    """Экран настроек с погашенными живыми значениями.

    Гасится всё, что движок пишет сам: громкость числом, ползунок целиком
    (его ручка ездит) и колонка значений статистики. Подписи, заголовки
    и пояснения остаются нарисованными — они постоянные.

    Источник фона у каждой заплатки берётся на ТЕХ ЖЕ строках, только правее,
    где панель пуста. Общий источник на всех (полоса между статистикой
    и кнопками) пробовался и не подошёл: панель темнеет к краям, и принесённый
    с другой высоты фон ложился светлой полосой ровно там, где заплатка.
    """
    im = Image.open(SRC / "меню.png").convert("RGB")

    # «35%»: слева на этих строках заголовок «ГРОМКОСТЬ МУЗЫКИ», чисто с 450.
    cover(im, (1024, 264, 1152, 332), (700, 264, 828, 332))
    # Ползунок целиком — ручка ездит, движок рисует свой.
    cover(im, (52, 326, 844, 394), (850, 326, 1140, 394))
    # Колонка значений статистики. Самая длинная подпись кончается на 321.
    cover(im, (330, 636, 782, 1078), (800, 636, 1140, 1078))
    # Значение в строке «Ранг:» стоит левее прочих — подпись кончается на 147.
    # Заплатка заходит под соседнюю с запасом: на стыке двух растворённых
    # краёв прозрачность проседает, и в шве оставался кусок старого значения.
    cover(im, (196, 634, 420, 702), (800, 634, 1024, 702))
    return im


def choice_screen() -> Image.Image:
    """Экран выбора бонуса — как есть, живых значений нет."""
    return Image.open(SRC / "скипнуть день ног.png").convert("RGB")


def topup_screen() -> Image.Image:
    """Экран пополнения — как есть: порции нарисованы и не меняются."""
    return Image.open(SRC / "взять монеты.png").convert("RGB")


def main() -> int:
    for name in ("цепь.png", "правила (2).png", "меню.png", "скипнуть день ног.png", "взять монеты.png"):
        if not (SRC / name).exists():
            print(f"  Не найден исходник: {SRC / name}")
            return 1

    UI.mkdir(parents=True, exist_ok=True)
    for image, dest in (
        (oil_panel(), "oil-panel.png"),
        (rules_screen(), "rules-screen.png"),
        (menu_screen(), "menu-screen.png"),
        (choice_screen(), "choice-screen.png"),
        (topup_screen(), "topup-screen.png"),
    ):
        image.save(UI / dest)
        print(f"  {dest:18s} {image.size[0]}x{image.size[1]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
