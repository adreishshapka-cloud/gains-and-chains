def rules_screen() -> Image.Image:
    """Экран правил с исправленными опечатками.

    Числа не гасятся: на этом экране всё постоянное, и живого здесь нет
    ни одного значения. Чтобы картинка не разошлась с мат-моделью молча,
    её числа закреплены тестом (src/ui/rulesArt.test.ts) — тронешь выплаты,
    двери или цену покупки, и тест упадёт с требованием перерисовать экран.
    """
    im = Image.open(SRC / "правила.png").convert("RGB")

    # «Португлея» -> «Портупея». Буквы слова: П 121, о 136, р 149, т 161,
    # у 172, гл 184..203, е 206, я 219..229; строчные сидят на 559..573.
    # Донор «п» — из «Напульсник» строкой ниже (x 149..159, 600..614),
    # шаг строк таблицы ровно 41 пиксель. Хвост «ея» переезжает влево на
    # разницу ширины: «гл» занимало 19 пикселей, «п» занимает 11.
    letter_p = glyph(im, (149, 600, 160, 615))
    tail = glyph(im, (206, 559, 230, 574))
    # Заплатка шире слова на десяток пикселей: у неё растворённый край,
    # и вставший впритык хвост старого «я» просвечивал сквозь него.
    cover(im, (182, 550, 252, 588), (256, 550, 326, 588))
    im.paste(letter_p, (184, 559))
    im.paste(tail, (198, 559))

    # «цели» -> «цепи», обе строки блока OIL UP. Донор «п» — из слова «пятом»
    # второй строки (x 905..912, 437..447); первая строка выше на 26 пикселей.
    small_p = glyph(im, (905, 437, 913, 448))
    for lx, ly, ix1, ix2 in (
        # л, строка «Золотые цели несут…»: x 975..984, и — 986..994
        (975, 411, 986, 995),
        # л, строка «…забирает все цели…»: x 1178..1186, и — 1189..1196
        (1178, 437, 1189, 1197),
    ):
        letter_i = glyph(im, (ix1, ly, ix2, ly + 11))
        width = ix2 + 5 - (lx - 3)
        cover(im, (lx - 3, ly - 7, ix2 + 5, ly + 17), (1380, ly - 7, 1380 + width, ly + 17))
        im.paste(small_p, (lx, ly))
        im.paste(letter_i, (lx + 10, ly))

    return im


