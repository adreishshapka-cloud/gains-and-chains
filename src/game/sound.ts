import { Howl } from 'howler';
import spinUrl from '../assets/audio/spin.mp3';

/**
 * Звуковые эффекты. Пока один — остановка барабана.
 *
 * Отдельно от музыки намеренно: у них разные выключатели (кнопки «динамик»
 * и «нота»), разная громкость и разное поведение — музыка зациклена и одна
 * на комнату, эффект короткий и звучит по нескольку раз за спин.
 *
 * Звучит именно на остановку каждого барабана, а не один раз на нажатие
 * SPIN: пять щелчков подряд отбивают ритм падения, а один звук в начале
 * успевает отыграть раньше, чем барабаны вообще встанут.
 *
 * Наложение запрещено: барабаны встают с небольшим шагом, а в турбо — почти
 * подряд, и без обрыва предыдущего щелчки сливаются в кашу.
 */

/**
 * Громкость щелчка. Половина громкости терялась под музыкой — спин на слух
 * оставался беззвучным, хотя звук отыгрывал. Поднято до трёх четвертей:
 * щелчок слышно поверх темы, но он не забивает её собой.
 *
 * Ручку громкости эффектов игроку не даём: их всего один, и отдельный
 * ползунок ради него был бы шумом в настройках. Кнопка «динамик» гасит их
 * целиком — этого достаточно.
 */
const VOLUME = 0.75;

class SoundBoard {
  private spinSfx: Howl | null = null;
  private enabled = true;

  get isOn(): boolean {
    return this.enabled;
  }

  setEnabled(on: boolean): void {
    this.enabled = on;
    if (!on) this.spinSfx?.stop();
  }

  reelStop(): void {
    if (!this.enabled) return;
    // Howl создаётся при первом обращении, а не при загрузке модуля: до первого
    // действия игрока браузер всё равно не даст ничего воспроизвести.
    this.spinSfx ??= new Howl({ src: [spinUrl], volume: VOLUME, html5: false });
    this.spinSfx.stop();
    this.spinSfx.play();
  }
}

export const sound = new SoundBoard();
