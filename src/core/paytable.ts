/**
 * Номиналы золотых цепей (OIL UP), в ОБЩИХ ставках, с весами.
 * Сильный перекос к мелким: редкая крупная цепь должна ощущаться событием,
 * а не просто очередным числом.
 *
 * Ступеней ровно пять, и каждая имеет свой цвет металла (см. CHAIN_TIER_COLOR).
 * Восемь ступеней различались только числом на спрайте, а число на крутящемся
 * барабане прочитать невозможно — цвет считывается мгновенно. Веса подобраны
 * так, чтобы средний номинал остался прежним и вклад фичи в RTP не поехал.
 */
export const CHAIN_VALUES: readonly { value: number; weight: number }[] = [
  { value: 1, weight: 640 },
  { value: 2, weight: 250 },
  { value: 5, weight: 110 },
  { value: 20, weight: 35 },
  { value: 100, weight: 5 },
];

/** Цвет ступени. Порядок совпадает с CHAIN_VALUES: бронза → серебро → золото → фиолет → красный. */
export const CHAIN_TIER_COLOR: readonly number[] = [
  0xb87333, // бронза
  0xc3c9d6, // серебро
  0xffd24a, // золото
  0xa64bd8, // фиолет
  0xd4453a, // красный
];

/** Индекс ступени по номиналу — по нему выбирается спрайт и цвет подписи. */
export function chainTier(value: number): number {
  const i = CHAIN_VALUES.findIndex((c) => c.value === value);
  return i < 0 ? 0 : i;
}

export const CHAIN_WEIGHT_TOTAL = CHAIN_VALUES.reduce((s, c) => s + c.weight, 0);

/** Средний номинал цепи — для быстрой прикидки вклада фичи в RTP без симуляции. */
export const CHAIN_AVG_VALUE =
  CHAIN_VALUES.reduce((s, c) => s + c.value * c.weight, 0) / CHAIN_WEIGHT_TOTAL;
