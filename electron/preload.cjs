/**
 * Мост между окном игры и главным процессом.
 *
 * Наружу выставлено ровно одно действие — переключить полный экран. Браузерный
 * requestFullscreen в упакованном приложении капризен: он требует доверенного
 * жеста и умеет отказывать без внятной причины, а окно Electron переводится
 * в полноэкранный режим напрямую и всегда.
 *
 * Ничего кроме этого сюда добавлять не нужно: игра считает числа и рисует
 * картинки, доступ к системе ей не требуется.
 */

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('desktop', {
  toggleFullscreen: () => ipcRenderer.invoke('toggle-fullscreen'),
});
